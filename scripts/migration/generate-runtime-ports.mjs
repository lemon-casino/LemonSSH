"use strict";

// Generates infrastructure/runtime/generated/runtimePorts.ts from the frozen
// Electron bridge contract fixtures (P0-01). The generated module splits the
// NetcattyBridge surface into shell-neutral domain ports that the Wails
// RuntimeClient adapter (P1-02) must implement with the same shapes.
//
// Coverage rule enforced by --check: every bridge method in the contract index
// and the plugin block of global.d.ts belongs to exactly one port.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const contractIndexPath = path.join(repoRoot, "testdata", "migration", "electron", "bridge-contract-index.json");
const globalDtsPath = path.join(repoRoot, "global.d.ts");
const outputPath = path.join(repoRoot, "infrastructure", "runtime", "generated", "runtimePorts.ts");

// Port name per contract-index source file. One port per declaration source
// keeps the grouping mechanical; finer domain splits (credential, window,
// profile) happen deliberately in their replacement slices (P2-04, P2-07,
// P4-02), not in this view layer.
const SOURCE_PORTS = [
  { source: "types/global/netcatty-bridge-app.d.ts", port: "AppPort", doc: "App shell: update, tray panel, hotkeys, deep links, proxy." },
  { source: "types/global/netcatty-bridge-ai.d.ts", port: "AgentPort", doc: "AI providers, Catty, external agents and MCP integrations." },
  { source: "types/global/netcatty-bridge-files.d.ts", port: "FilesPort", doc: "Local filesystem, dialogs, temp files, clipboard and credentials." },
  { source: "types/global/netcatty-bridge-script.d.ts", port: "ScriptPort", doc: "Script recording, runs and automation dialogs." },
  { source: "types/global/netcatty-bridge-session.d.ts", port: "TerminalPort", doc: "Terminal sessions: PTY/SSH/telnet/serial/mosh/ET and ZMODEM." },
  { source: "types/global/netcatty-bridge-sftp.d.ts", port: "SftpPort", doc: "SFTP browsing and transfer scheduling." },
  { source: "types/global/netcatty-bridge-sync.d.ts", port: "SyncPort", doc: "Cloud/convergent sync, vault backups, app lock, windows and port forwarding." },
  { source: "types/global/netcatty-bridge-system.d.ts", port: "SystemPort", doc: "System inspection: docker, tmux, processes, services, popup terminal." },
];

const PLUGIN_PORT = { port: "PluginPort", doc: "Plugin runtime, packages, contributions and terminal providers." };

function parsePluginMethods(source) {
  const interfaceMatch = source.match(/interface NetcattyBridge \{([^]*)\n  \}/);
  if (!interfaceMatch) throw new Error("NetcattyBridge interface not found in global.d.ts");
  const methods = [];
  for (const line of interfaceMatch[1].split("\n")) {
    const match = line.match(/^\s{4}(\w+)\?\(/);
    if (match) methods.push(match[1]);
  }
  return methods;
}

function buildModel() {
  const contractIndex = JSON.parse(fs.readFileSync(contractIndexPath, "utf8"));
  const bySource = new Map(contractIndex.map((entry) => [entry.source, entry]));
  const ports = [];
  const seen = new Map();
  const duplicates = [];

  for (const { source, port, doc } of SOURCE_PORTS) {
    const entry = bySource.get(source);
    if (!entry) throw new Error(`contract index is missing source: ${source}`);
    const methods = [...new Set(entry.methods.map((method) => method.name || method))];
    for (const method of methods) {
      if (seen.has(method)) duplicates.push(`${method} in ${port} and ${seen.get(method)}`);
      seen.set(method, port);
    }
    ports.push({ port, doc, methods, source });
  }

  const pluginMethods = parsePluginMethods(fs.readFileSync(globalDtsPath, "utf8"));
  for (const method of pluginMethods) {
    if (seen.has(method)) duplicates.push(`${method} in PluginPort and ${seen.get(method)}`);
    seen.set(method, PluginPortName());
  }
  ports.push({ port: PLUGIN_PORT.port, doc: PLUGIN_PORT.doc, methods: pluginMethods, source: "global.d.ts (NetcattyBridge block)" });

  return { ports, duplicates, totalMethods: seen.size };
}

function PluginPortName() {
  return PLUGIN_PORT.port;
}

function renderModule(model) {
  const out = [];
  out.push("// GENERATED FILE - DO NOT EDIT.");
  out.push("// Generated by scripts/migration/generate-runtime-ports.mjs from");
  out.push("// testdata/migration/electron/bridge-contract-index.json and global.d.ts.");
  out.push("// Shell-neutral domain ports for the migration RuntimeClient (P1-01).");
  out.push("");
  for (const { port, doc, methods } of model.ports) {
    out.push(`/** ${doc} */`);
    out.push(`export type ${port} = Pick<NetcattyBridge, ${methods.map((m) => JSON.stringify(m)).join(" | ")}>;`);
    out.push("");
  }
  out.push("/** Domain-grouped, shell-neutral view of the full bridge surface. */");
  out.push("export interface RuntimePorts {");
  for (const { port } of model.ports) {
    out.push(`  ${port.charAt(0).toLowerCase()}${port.slice(1, -4)}: ${port};`);
  }
  out.push("}");
  out.push("");
  return `${out.join("\n")}\n`;
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const model = buildModel();
  if (model.duplicates.length > 0) {
    console.error("Port membership is not disjoint:");
    for (const duplicate of model.duplicates) console.error(`  ${duplicate}`);
    process.exit(1);
  }
  const contents = renderModule(model);
  if (checkOnly) {
    const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
    if (existing !== contents) {
      console.error("runtimePorts.ts is stale; run: npm run generate:runtime-ports");
      process.exit(1);
    }
    console.log(`runtimePorts.ts up to date (${model.totalMethods} methods across ${model.ports.length} ports)`);
    return;
  }
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, contents, "utf8");
  console.log(`Wrote ${path.relative(repoRoot, outputPath)} (${model.totalMethods} methods across ${model.ports.length} ports)`);
}

main();
