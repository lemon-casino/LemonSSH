func TestRunnerPauseAndResume(t *testing.T) {
	runner := NewRunner(func(sessionID string, data []byte) error { return nil })
	writes := make(chan string, 4)
	runner.SetWriter(func(sessionID string, data []byte) error {
		writes <- string(data)
		return nil
	})
	run, err := runner.Start(StartRunRequest{
		SessionID: "s1",
		Content: `async function main() {
  await nct.screen.sendLine("one");
  await nct.screen.sendLine("two");
}
await main();`,
	})
	if err != nil {
		t.Fatal(err)
	}
	if first := <-writes; first != "one" {
		t.Fatalf("first write %q", first)
	}
	if !runner.Pause(run.RunID) {
		t.Fatal("pause failed")
	}
	if runner.Pause(run.RunID) {
		t.Fatal("double pause must fail")
	}
	time.Sleep(30 * time.Millisecond)
	drainDeadline := time.Now().Add(100 * time.Millisecond)
	for {
		select {
		case <-writes:
			continue
		case <-time.After(time.Until(drainDeadline)):
		}
		break
	}
	if len(writes) != 0 {
		t.Fatalf("writes while paused = %d", len(writes))
	}
	if !runner.Resume(run.RunID) {
		t.Fatal("resume failed")
	}
	if second := <-writes; second != "two" {
		t.Fatalf("second write %q", second)
	}
	if third := <-writes; third != "\r" {
		t.Fatalf("third write %q", third)
	}
	deadline := time.Now().Add(2 * time.Second)
	for {
		listed := runner.List("s1")
		if len(listed) == 1 && listed[0].Status == "completed" {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("run stuck: %#v", listed)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func TestParseAndRunProgressScript(t *testing.T) {
	runner := NewRunner(func(sessionID string, data []byte) error { return nil })
	_, err := runner.Start(StartRunRequest{
		SessionID: "s1",
		Content: `async function main() {
  nct.progress.start("Inventory", 2);
  nct.progress.set(1, "halfway");
  nct.progress.step();
  nct.progress.done();
}
await main();`,
	})
	if err != nil {
		t.Fatal(err)
	}
	deadline := time.Now().Add(2 * time.Second)
	for {
		listed := runner.List("s1")
		if len(listed) == 1 && listed[0].Status == "completed" {
			if listed[0].ProgressMode != "determinate" || listed[0].ProgressCurrent != 2 || listed[0].ProgressTotal != 2 {
				t.Fatalf("progress: %#v", listed[0])
			}
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("run state: %#v", listed)
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func TestRunnerDisconnectCompletesWithoutFurtherWrites(t *testing.T) {
	runner := NewRunner(func(sessionID string, data []byte) error {
		t.Fatal("must not write after disconnect")
		return nil
	})
	var closed []string
	runner.SetSessionCloser(func(sessionID string) error {
		closed = append(closed, sessionID)
		return nil
	})
	_, err := runner.Start(StartRunRequest{
		SessionID: "s1",
		Content: `async function main() {
  await nct.session.disconnect();
  await nct.screen.sendLine("never");
}
await main();`,
	})
	if err != nil {
		t.Fatal(err)
	}
	deadline := time.Now().Add(2 * time.Second)
	for {
		listed := runner.List("s1")
		if len(listed) == 1 && listed[0].Status == "completed" {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("run state: %#v", listed)
		}
		time.Sleep(10 * time.Millisecond)
	}
	if len(closed) != 1 || closed[0] != "s1" {
		t.Fatalf("closed: %#v", closed)
	}
	if _, err := ParseRecordedScript(`async function main() {
  await nct.session.startLog();
}
await main();`); err == nil || !strings.Contains(err.Error(), "not migrated") {
		t.Fatalf("startLog must stay rejected: %v", err)
	}
}

func TestRunnerWaitForPromptSeesSessionOutput(t *testing.T) {
	wrote := make(chan string, 2)
	runner := NewRunner(func(sessionID string, data []byte) error {
		wrote <- string(data)
		return nil
	})
	go func() {
		time.Sleep(20 * time.Millisecond)
		runner.ObserveOutput("s1", []byte("root@host:/data# "))
	}()
	run, err := runner.Start(StartRunRequest{
		SessionID: "s1",
		Content: `async function main() {
  await nct.screen.sendLine("ls");
  await nct.screen.waitForPrompt(1000);
}
await main();`,
	})
	if err != nil {
		t.Fatal(err)
	}
	deadline := time.Now().Add(time.Second)
	for {
		listed := runner.List("s1")
		if len(listed) == 1 && listed[0].Status == "completed" {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("run did not complete: %#v", listed)
		}
		time.Sleep(10 * time.Millisecond)
	}
	if run.RunID == "" {
		t.Fatal("missing run id")
	}
	select {
	case <-wrote:
	case <-time.After(time.Second):
		t.Fatal("sendLine did not write")
	}
}
